/* ------------------------------------------------------------------ 组装 */
export function buildPrompt(skin, mood) {
  const costume = COSTUMES[skin]
  const pose = POSES[mood]
  if (!costume) throw new Error('未知皮肤：' + skin)
  if (!pose) throw new Error('未知情绪：' + mood)
  return [GREEN, IDENTITY, costume, BODY, STYLE, pose, CHECKLIST, COMPOSITION].join('\n\n')
}

export const PARAMS = {
  model: 'gpt',
  resolution: '4K',
  target_size: '2048x3072',
  aspect_ratio: '2:3',
  quality: 'high',
  thinking_level: 'high',
  /* 纯文生图：这一项必须是空数组，并且写进 manifest 让审计能证明。 */
  reference_images: [],
}

export function buildManifest(skin) {
  return MOODS.map((mood) => ({
    name: skin + '_' + mood,
    prompt: buildPrompt(skin, mood),
    skin,
    mood,
    params: PARAMS,
  }))
}

/* -------------------------------------------------------------------- CLI */
const args = process.argv.slice(2)
const valueOf = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null }

if (args.includes('--print')) {
  const i = args.indexOf('--print')
  console.log(buildPrompt(args[i + 1], args[i + 2]))
} else if (args.includes('--manifest')) {
  const dir = resolve(here, valueOf('--manifest') || '.out')
  mkdirSync(dir, { recursive: true })
  for (const skin of SKINS_V2) {
    writeFileSync(join(dir, 'manifest-' + skin + '.json'), JSON.stringify(buildManifest(skin), null, 1), 'utf8')
  }
  console.log('写出一套一个 manifest：' + SKINS_V2.length + ' 个 -> ' + dir)
} else if (args.includes('--stats')) {
  /* 自检：同一套皮肤八张的正文，除【姿态】段外必须逐字相同；服装必须同时在规格段与末尾清单里。 */
  let bad = 0
  for (const skin of SKINS_V2) {
    const base = buildPrompt(skin, 'idle').split('\n\n').filter((s) => !s.startsWith('【姿态】'))
    for (const mood of MOODS) {
      const parts = buildPrompt(skin, mood).split('\n\n').filter((s) => !s.startsWith('【姿态】'))
      if (JSON.stringify(parts) !== JSON.stringify(base)) { console.log('✗ ' + skin + '/' + mood + ' 除姿态外仍有差异'); bad++ }
    }
    const p = buildPrompt(skin, 'idle')
    if (!/【服装规格】/.test(p) || !/⑧ 服装必须与上面【服装规格】/.test(p)) {
      console.log('✗ ' + skin + ' 服装没有同时出现在规格段与末尾清单'); bad++
    }
  }
  console.log('皮肤 ' + SKINS_V2.length + ' 套 × 情绪 ' + MOODS.length + ' 张 = ' + SKINS_V2.length * MOODS.length + ' 张')
  console.log('正文字数（classic/idle）：' + buildPrompt('classic', 'idle').length)
  console.log(bad === 0 ? '自检通过：八张正文除【姿态】外逐字相同，服装同时在规格段与末尾清单里。'
    : '自检失败：' + bad + ' 项')
  process.exit(bad === 0 ? 0 : 1)
} else {
  console.log('用法：--manifest <dir> | --print <skin> <mood> | --stats')
}
